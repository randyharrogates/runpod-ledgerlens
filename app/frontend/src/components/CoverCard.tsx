import { useEffect, useState } from 'react';
import { api, CoverState } from '../api';

type Figures = {title: string; subtitle: string; facts: [string, string][]};
export const coverLabel = 'Illustration generated by FLUX.1-dev from a prompt built from the documents. Not evidence. All figures are computed from the checked statement rows.';
export function CoverView({state, title, subtitle, facts, elapsed = 0, prompt = state.prompt || '', setPrompt, regenerate}: Figures & {
  state: CoverState; elapsed?: number; prompt?: string; setPrompt?: (value: string) => void; regenerate?: () => void;
}) {
  const running = state.status === 'running';
  return <section className="cover-card" aria-label="Memo cover">
    <div className={`cover-art ${state.image ? 'cover-with-image' : ''}`}>
      {state.image && <img src={state.image} alt={`AI illustration: ${state.industry} business in ${state.country}`} />}
      {running && <div className="cover-progress" role="status">Painting the cover illustration · {Math.floor(elapsed / 60)}:{String(elapsed % 60).padStart(2, '0')}
        {elapsed >= 20 && <small>The image GPU may be starting; this can take a few minutes.</small>}
      </div>}
      <div className="cover-overlay"><h2>{title}</h2><p>{subtitle}</p>
        <dl>{facts.map(([label, value]) => <div key={label}><dt>{label}</dt><dd>{value}</dd></div>)}</dl>
      </div>
    </div>
    <div className="cover-caption"><p>{coverLabel}</p>
      {state.auto && <p>Prompt built from: {state.basis?.join(', ') || 'general trading'}</p>}
      {state.metrics && <p>Generated in {((state.metrics.executionTime || 0) / 1000).toFixed(1)} s on {state.metrics.gpu || 'GPU'} · ${(state.metrics.cost || 0).toFixed(4)}</p>}
      {state.error && <p className="error">{state.error}</p>}
      <details className="print-control"><summary>Edit prompt</summary>
        <textarea aria-label="Cover illustration prompt" value={prompt} disabled={running} onChange={event => setPrompt?.(event.target.value)} />
        <button disabled={running || !prompt.trim()} onClick={regenerate}>Regenerate</button>
      </details>
    </div>
  </section>;
}

export function CoverCard({session, autoStart, ...figures}: Figures & {session: string; autoStart: boolean}) {
  const [state, setState] = useState<CoverState>({status: 'idle'});
  const [prompt, setPrompt] = useState('');
  const [now, setNow] = useState(Date.now());
  useEffect(() => {
    let active = true;
    const accept = (value: CoverState) => {
      if (!active) return;
      setState(value); setPrompt(value.prompt || ''); setNow(Date.now());
    };
    const fail = (error: Error) => { if (active) setState(value => ({...value, status: 'error', error: error.message})); };
    void api.cover(session).then(async value => {
      if (!active) return;
      accept(value.status === 'idle' && autoStart ? await api.startCover(session, {}) : value);
    }).catch(fail);
    return () => { active = false; };
  }, [session, autoStart]);
  useEffect(() => {
    if (state.status !== 'running') return;
    let active = true;
    let timer: ReturnType<typeof setTimeout>;
    const poll = async () => {
      try {
        const value = await api.cover(session);
        if (!active) return;
        setNow(Date.now()); setState(value);
        if (value.prompt) setPrompt(value.prompt);
        if (value.status === 'running') timer = setTimeout(() => void poll(), 2000);
      } catch (error) {
        if (active) setState(value => ({...value, status: 'error', error: (error as Error).message}));
      }
    };
    timer = setTimeout(() => void poll(), 2000);
    return () => { active = false; clearTimeout(timer); };
  }, [session, state.status]);
  const regenerate = async () => {
    try { const value = await api.startCover(session, {prompt, force: true}); setState(value); setPrompt(value.prompt || ''); }
    catch (error) { setState(value => ({...value, error: (error as Error).message})); }
  };
  return <CoverView {...figures} state={state} elapsed={Math.max(0, Math.floor((now / 1000) - (state.started || now / 1000)))} prompt={prompt} setPrompt={setPrompt} regenerate={() => void regenerate()} />;
}
